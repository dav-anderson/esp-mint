//! The versions of the libraries a build locked, read from its `Cargo.lock` by
//! `build.rs` (which includes this file) so that `esp-mint --version` can say
//! what the program was built with. Nothing else uses it.

/// The version of each package in `names` that `lock` (the text of a
/// `Cargo.lock`) holds, as `(name, version)`, in the order of `names`. A package
/// locked at two versions gives the first; one the lock does not hold is left
/// out.
pub fn versions(lock: &str, names: &[&str]) -> Vec<(String, String)> {
    let mut found: Vec<(String, String)> = Vec::new();
    let mut name: Option<&str> = None;
    for line in lock.lines() {
        let line = line.trim();
        if line == "[[package]]" {
            name = None;
        } else if let Some(value) = line.strip_prefix("name = ") {
            name = Some(value.trim_matches('"'));
        } else if let Some(value) = line.strip_prefix("version = ")
            && let Some(n) = name
            && names.contains(&n)
            && !found.iter().any(|(f, _)| f == n)
        {
            found.push((n.to_string(), value.trim_matches('"').to_string()));
        }
    }
    names
        .iter()
        .filter_map(|n| found.iter().find(|(f, _)| f == n).cloned())
        .collect()
}

#[cfg(test)]
mod tests {
    use super::*;

    const LOCK: &str = r#"# This file is automatically @generated by Cargo.
version = 4

[[package]]
name = "air"
version = "3.0.0"
source = "registry+https://github.com/rust-lang/crates.io-index"

[[package]]
name = "air"
version = "2.0.3"

[[package]]
name = "mint-core"
version = "0.1.3"
source = "git+https://github.com/dav-anderson/mint-core.git?tag=v0.1.3#1366acec7a7550a220dc287995b6d2af5e93cefc"

[[package]]
name = "sp-wire"
version = "0.5.1"
dependencies = [
 "air",
]

[[package]]
name = "serde"
version = "1.0.200"
"#;

    #[test]
    fn the_locked_versions_come_in_the_order_asked_and_skip_what_is_not_locked() {
        assert_eq!(
            versions(LOCK, &["sp-wire", "air_server", "mint-core", "air"]),
            vec![
                ("sp-wire".to_string(), "0.5.1".to_string()),
                ("mint-core".to_string(), "0.1.3".to_string()),
                ("air".to_string(), "3.0.0".to_string()),
            ]
        );
        assert!(versions("", &["sp-wire"]).is_empty());
    }
}
